#!/usr/bin/env node
//
//  ux-gate — напоминает про тексты ровно один раз, перед отправкой
//  ──────────────────────────────────────────────────────────────
//
//  ЗАЧЕМ ЭТО НУЖНО
//  Свод правил о текстах агент по своей воле не открывает — так решено: он не должен
//  переписывать ваши формулировки без спроса. Но есть один момент, когда спросить надо:
//  когда работа уходит к команде — pull request. После этого текст читают все, и «потом поправим» уже не работает.
//
//  Проверка ловит этот момент и просит агента предложить вам проверку. Один раз за
//  разговор: сказали «не надо» — та же команда пройдёт сразу.
//
//  КОГДА ОН ЗАПУСКАЕТСЯ
//  Сам, когда агент собирается открыть pull request. Обычный пуш не трогает.
//
//  ЧТО ВЫ УВИДИТЕ
//  Вопрос от агента: проверить тексты перед отправкой? Ответ — ваш, оба варианта
//  нормальные. Проверка ничего не запрещает, она не даёт отправить молча.
//
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

let input = {}
try { input = JSON.parse(fs.readFileSync(0, 'utf8')) } catch { process.exit(0) }

const cmd = input.tool_input?.command || ''
// Только pull request. Пуш в свою ветку — рабочий момент, его видит один автор;
// PR читает команда, вот там и уместно спросить. Останавливать пуш значило бы
// запрещать дизайнеру то, что он сам попросил.
if (!/\bgh\s+pr\s+create\b/.test(cmd)) process.exit(0)

const root = input.cwd || process.env.CLAUDE_PROJECT_DIR || process.cwd()

// Свода нет — проверять нечем, молчим.
if (!fs.existsSync(path.join(root, 'vendor', 'uxw', 'ux-check', 'SKILL.md'))) process.exit(0)

// Один раз за разговор: иначе после отказа дизайнера отправка станет невозможной.
const flag = path.join(os.tmpdir(), 'ux-gate-' + (input.session_id || 'x'))
if (fs.existsSync(flag)) process.exit(0)
fs.writeFileSync(flag, '1')

console.log(JSON.stringify({
  hookSpecificOutput: {
    hookEventName: 'PreToolUse',
    permissionDecision: 'deny',
    permissionDecisionReason:
      'Работа уходит наружу, а тексты интерфейса не проверены по своду правил Xsolla. ' +
      'Спроси дизайнера одним вопросом: проверить тексты перед отправкой (`/ux`) или отправлять как есть. ' +
      'Не проверяй сам без его ответа и не переписывай формулировки по своей инициативе. ' +
      'Что он ответит, то и делай — эта проверка больше за разговор не сработает, повторная команда пройдёт.',
  },
}))
